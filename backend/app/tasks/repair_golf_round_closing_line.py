"""CAL-P1081 (#938) — golf round markets stop publishing an opening-day stamp as a closing line.

## the defect, in one specimen

``KXDPWORLDTOURR1LEAD-HEIO26`` and its siblings publish
``calibration_probability = 0.990000`` for twenty-three golfers who cannot all
lead a round. The number is not a price anybody quoted: for those same legs the
LAST Kalshi snapshot before the round starts reads ``0.070``, ``0.380``,
``0.350``, ``0.740`` — real, observed, and sitting in ``futures_odds_snapshots``
the whole time. The published 0.99 is the market's OPENING stamp, carried
forward because the closing line was never computed.

Measured on production 2026-09-10 over the 286 round-scoped Kalshi golf markets
(``artifacts-calibration-1081``): **2,035 outcomes** are in this state —
1,382 ``…LEAD`` legs whose stored price averages **0.4269** against a true
last-pre-commence snapshot averaging **0.1524**, and 653 ``…TOP{N}`` legs at
0.7524 against 0.6575. The published win rate of the ``lead`` arm is ~1% at
EVERY price decile from 0.03 to 0.95, which is the signature of a stamp rather
than a forecast.

## THIS RAIL INVENTS NO PRICE RULE. IT FINISHES ONE THAT ALREADY SHIPPED.

``backfill_winners._backfill_calibration_prices`` Part A2 already owns this
exact correction. Its reset selects rows where ``calibration_probability =
opening_probability`` **and** the snapshot it would pick differs from the
opening; its refill then writes that snapshot. Both halves are budget-gated
(``_cal_remaining()`` / ``_RESET_MIN_BUDGET_S``), and the pipeline has been
stopping early for weeks — CAL-P1080 measured ``partial_budget_guard``,
``stopped_before: bookmaker_closing``, 757.8s of an 840s limit. So the rows
below are not rows Part A2 judges differently; they are rows it never reached.

Everything this module decides is therefore Part A2's decision, copied by
reference rather than by opinion:

* **which snapshot is the closing line** — the last one strictly BEFORE
  ``commence_time`` with ``0 < probability < 1``, ordered ``captured_at DESC``.
  Strictly before, because a price captured after the answer is not a price
  (ruling 103).
* **which rows are candidates** — ``calibration_probability`` present and equal
  to ``opening_probability`` (the tell of the opening-stamp fallback), and that
  closing snapshot exists and differs from the opening.
* **what is written** — the snapshot's own probability. Nothing is scaled,
  clamped, normalized or thresholded here. There is no constant in this module
  that a price is compared against, and
  ``test_the_rail_holds_no_price_rule_of_its_own`` fails if one appears.

A row this rail repairs is a row Part A2 would repair on a run that finished.
That is the whole safety argument, and it is why the fix is a repair and not a
new policy: the alternative — a curve-side exclusion — is impossible anyway,
because ``precompute_calibration.py`` is frozen (ruling 009, lift condition
unmet).

## the bound, and why it is a predicate rather than an id list

The sibling rails (``repair_kalshi_senate_category``) enumerate ids because
their population is eight rows. This one is 286 markets / ~29k outcomes, so the
bound is the queue's named population expressed once, here:

    source kalshi · resolved · llm_sport_category 'golf' · event_id IS NULL
    · commence_time present · external_id LIKE 'KX%'
    · first ticker segment matches ROUND_SERIES_PATTERN

:data:`ROUND_SERIES_PATTERN` is ANCHORED (``R{digits}(LEAD|TOP{digits})$``)
where the published ``golfround`` dimension's own expression is not (it tests a
bare ``R[0-9]`` anywhere in the segment, which would also match the ``R2`` in a
hypothetical ``…TOUR2026``). Measured on production: both select **exactly the
same 286 markets** today, so the anchor costs nothing and removes a
false-positive class the loose form leaves open. That equality is a
measurement, recorded here, not an assumption — see
``test_the_anchored_pattern_cannot_match_a_year``.

Tournament-scoped golf is deliberately OUT. It measures 2.12/2.42 ECE against
these arms' 14.86/8.58; #938's title groups the two together and that is a
correction this repair records rather than inherits.

## D51 — backup and restore

``repair()`` returns every planned row with its ``before`` value, on the dry run
too, and ``apply=True`` logs the restore. The undo is generated by
:func:`restore_sql`, grouped one statement per distinct before-value so the
emitted text is always runnable SQL. For a population this size the payload is
written to an artifact by the caller; the log line carries the statement count
and the id range so an operator can find it.
"""

from __future__ import annotations

import logging
from typing import Any

from sqlalchemy import text

logger = logging.getLogger(__name__)


#: The round-scoped Kalshi golf series, as a POSIX regex over the first
#: hyphen-separated segment of ``futures_markets.external_id``.
#:
#: Anchored on purpose (see the module docstring). ``KXDPWORLDTOURR1LEAD`` and
#: ``KXPGAR1TOP5`` match; ``KXPGATOURWINNER`` and a year-bearing
#: ``…TOUR2026`` cannot.
ROUND_SERIES_PATTERN = r"R[0-9]+(LEAD|TOP[0-9]+)$"

#: The published ``golfround`` dimension's own, looser, test. Kept ONLY so the
#: guard can assert the two agree on production's population; never used to
#: select a row here.
PUBLISHED_DIMENSION_PATTERN = r"R[0-9]"

#: The bound. One rendering, used by the plan and the apply alike, so the two
#: cannot drift apart.
_BOUND_SQL = """
    SELECT fm.id AS market_id, fm.external_id, fm.commence_time
    FROM futures_markets fm
    WHERE fm.source = 'kalshi'
      AND fm.status = 'resolved'
      AND fm.llm_sport_category = 'golf'
      AND fm.event_id IS NULL
      AND fm.commence_time IS NOT NULL
      AND fm.external_id LIKE 'KX%'
      AND SPLIT_PART(fm.external_id, '-', 1) ~ :round_pattern
"""

#: Part A2's closing-line selector, copied by reference. The ``captured_at <
#: commence_time`` bound is ruling 103 and is the one clause that must never be
#: relaxed: a snapshot taken after the round is under way is the answer, not a
#: forecast of it.
_CLOSING_LATERAL = """
    LEFT JOIN LATERAL (
        SELECT fos.probability
        FROM futures_odds_snapshots fos
        WHERE fos.outcome_id = fo.id
          AND fos.captured_at < b.commence_time
          AND fos.probability > 0 AND fos.probability < 1
        ORDER BY fos.captured_at DESC
        LIMIT 1
    ) closing ON true
"""

_PLAN_SQL = f"""
    WITH b AS ({_BOUND_SQL})
    SELECT fo.id AS outcome_id,
           b.market_id,
           b.external_id,
           fo.calibration_probability AS before_price,
           fo.opening_probability AS opening_price,
           closing.probability AS closing_price
    FROM b
    JOIN futures_outcomes fo ON fo.market_id = b.market_id
    {_CLOSING_LATERAL}
    WHERE fo.calibration_probability IS NOT NULL
      AND fo.opening_probability IS NOT NULL
      AND fo.calibration_probability = fo.opening_probability
    ORDER BY fo.id
"""

#: The write. Re-derives the closing price inside the UPDATE rather than
#: trusting the ids the plan produced: the plan and the apply may be seconds or
#: minutes apart, and a row Part A2 repaired in between must not be rewritten
#: from a stale reading. The predicate is the plan's predicate, so a row that
#: has moved simply falls out.
_APPLY_SQL = f"""
    WITH b AS ({_BOUND_SQL}),
    targets AS (
        SELECT fo.id AS outcome_id, closing.probability AS closing_price
        FROM b
        JOIN futures_outcomes fo ON fo.market_id = b.market_id
        {_CLOSING_LATERAL}
        WHERE fo.calibration_probability IS NOT NULL
          AND fo.opening_probability IS NOT NULL
          AND fo.calibration_probability = fo.opening_probability
          AND closing.probability IS NOT NULL
          AND closing.probability <> fo.opening_probability
    )
    UPDATE futures_outcomes fo
    SET calibration_probability = t.closing_price
    FROM targets t
    WHERE fo.id = t.outcome_id
"""

#: Refusal reasons, named so a reader of the payload never has to infer one.
REASON_NO_CLOSING_SNAPSHOT = "no_pre_commence_snapshot"
REASON_CLOSING_EQUALS_OPENING = "closing_equals_opening"


def restore_sql(planned: list[dict[str, Any]]) -> str:
    """The D51 undo, as ONE statement that pastes and runs.

    🔴 IT IS ONE STATEMENT BECAUSE OF WHAT THE GATE IS, not because the ids were
    grouped cleverly. Every planned row is by definition a row where
    ``calibration_probability = opening_probability`` — that equality IS the
    candidate test — so ``SET calibration_probability = opening_probability``
    over the changed ids restores each row to its own stored before-value
    exactly, without the statement having to carry 2,035 numbers.

    The first draft emitted one statement per distinct before-value (116 of
    them, 31 KB), which is runnable and is not "a one-command restore"; D51 is
    granted to a repair that ships one. ``before`` still travels on every record
    in the payload, so the numeric backup is not lost — it is simply not what
    the undo has to read.

    Scoped to the ids the plan actually names, never to the bound: if Part A2
    reprices one of these rows after the apply, that row must keep the pipeline's
    value, and a predicate-shaped restore would silently reclaim it.
    """
    ids = sorted(row["outcome_id"] for row in planned)
    if not ids:
        return ""
    ids_csv = ", ".join(str(i) for i in ids)
    return (
        "UPDATE futures_outcomes SET calibration_probability = opening_probability "
        f"WHERE id IN ({ids_csv});"
    )


async def repair(session, apply: bool = False) -> dict[str, Any]:
    """Plan (and optionally apply) the CAL-P1081 closing-line correction.

    Returns a payload complete enough to BE the D51 backup: every candidate row
    with its stored price, the closing line Part A2's selector picks for it, and
    either a plan or a named refusal.
    """
    rows = (
        await session.execute(text(_PLAN_SQL), {"round_pattern": ROUND_SERIES_PATTERN})
    ).all()

    planned: list[dict[str, Any]] = []
    refused: list[dict[str, Any]] = []

    for row in rows:
        record = {
            "outcome_id": row.outcome_id,
            "market_id": row.market_id,
            "external_id": row.external_id,
            "before": (
                None if row.before_price is None else float(row.before_price)
            ),
            "closing": (
                None if row.closing_price is None else float(row.closing_price)
            ),
        }
        if row.closing_price is None:
            # No price was ever observed before the round began. Part A2's own
            # fallback keeps the opening here, and so does this rail: the
            # alternative is to invent a number.
            refused.append({**record, "reason": REASON_NO_CLOSING_SNAPSHOT})
        elif row.closing_price == row.opening_price:
            # The stamp IS the closing line. Nothing to move.
            refused.append({**record, "reason": REASON_CLOSING_EQUALS_OPENING})
        else:
            planned.append(record)

    changed = 0
    if apply and planned:
        result = await session.execute(
            text(_APPLY_SQL), {"round_pattern": ROUND_SERIES_PATTERN}
        )
        await session.commit()
        changed = result.rowcount or 0
        logger.warning(
            "CAL-P1081 repair applied: %s outcomes repriced to their "
            "last pre-commence snapshot. D51 restore (one statement):\n%s",
            changed,
            restore_sql(planned),
        )

    return {
        "examined": len(rows),
        "planned": planned,
        "refused": refused,
        "changed": changed,
        "restore_sql": restore_sql(planned),
        "terminal": "changed" if apply else "dry_run",
    }
