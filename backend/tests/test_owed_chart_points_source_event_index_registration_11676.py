"""#11676: the per-event settle index is DECLARED in the model and BUILT only by hand.

PILLAR: TRUTH. SHIP: Polymarket chart-point confirmations keep their per-game
index, so no future autogenerated migration can silently drop it and bring back
the whole-table scan.

The ACK settle deletes a game's owed rows by ``(source, event_id)``. Before the
index, the Polymarket arm planned a Seq Scan over ~392k rows (cost 14,591). On
2026-10-28 ~19:04Z Alex ran the attended CREATE INDEX CONCURRENTLY build (29.8 s,
valid and ready); the same plan now reads ``Index Scan using
ix_owed_chart_points_source_event`` on both arms (cost 732). Runbook:
artifacts-authority-11676-backlog-a-or-b/RUNBOOK-ix_owed_chart_points_source_event.md.

``backend/alembic/env.py`` has no ``include_object`` filter, so an index that
exists in the database but not in ``models.py`` becomes an ``op.drop_index``
in the next autogenerated revision. Three things are pinned here:

1. The declared definition: exactly ``(source, event_id)``, non-unique, no
   predicate, no INCLUDE.
2. The compiled Postgres DDL is the statement that was built, minus
   CONCURRENTLY (and minus the default schema and method Postgres prints back).
3. No migration executes it. Gotcha #31: a concurrent build inside the release
   phase is the May 22 outage; a plain one locks out every stamp INSERT.

No database is needed. A guard for an attended index must not skip on the
machine that would change it.
"""

from __future__ import annotations

import ast
from pathlib import Path

from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex

from app.models.models import OwedChartPoint

INDEX_NAME = "ix_owed_chart_points_source_event"
# pg_indexes.indexdef read back after the attended build (post-check 1,
# artifacts/speed-index-11676-20261028/post/pc1.pre.out.json).
BUILT_INDEXDEF = (
    "CREATE INDEX ix_owed_chart_points_source_event ON public.owed_chart_points "
    "USING btree (source, event_id)"
)
# The same statement as SQLAlchemy compiles it: no schema, default method.
EXPECTED_PG_DDL = (
    "CREATE INDEX ix_owed_chart_points_source_event ON owed_chart_points (source, event_id)"
)

BACKEND = Path(__file__).resolve().parents[1]


def _the_index():
    matches = [i for i in OwedChartPoint.__table__.indexes if i.name == INDEX_NAME]
    assert len(matches) == 1, (
        f"{INDEX_NAME} must be declared exactly once on OwedChartPoint; found "
        f"{len(matches)}. Without the declaration the first --autogenerate after "
        "the attended build proposes dropping it."
    )
    return matches[0]


def _squash(sql: str) -> str:
    return " ".join(sql.split())


def test_the_declared_index_is_the_reviewed_definition() -> None:
    idx = _the_index()
    assert [c.name for c in idx.columns] == ["source", "event_id"]
    assert idx.unique is False
    assert idx.dialect_options["postgresql"]["where"] is None
    assert not idx.dialect_options["postgresql"]["include"]
    assert idx.dialect_options["postgresql"]["using"] in (False, None, "btree")


def test_the_compiled_postgres_ddl_is_the_built_statement() -> None:
    ddl = _squash(str(CreateIndex(_the_index()).compile(dialect=postgresql.dialect())))
    assert ddl == EXPECTED_PG_DDL
    # Postgres prints the default schema and method back; nothing else differs.
    assert BUILT_INDEXDEF.replace("public.", "").replace(" USING btree", "") == ddl


def _executed_strings(src: str) -> list[str]:
    """Every string literal in code that runs; docstrings and comments excluded.

    Raw index DDL here is triple-quoted SQL passed to ``op.execute``
    (add_discover_feed_indexes.py), so only docstring positions are skipped.
    """
    tree = ast.parse(src)
    docstrings = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            first = node.body[0] if node.body else None
            if (
                isinstance(first, ast.Expr)
                and isinstance(first.value, ast.Constant)
                and isinstance(first.value.value, str)
            ):
                docstrings.add(id(first.value))
    return [
        n.value
        for n in ast.walk(tree)
        if isinstance(n, ast.Constant) and isinstance(n.value, str) and id(n) not in docstrings
    ]


def test_no_migration_builds_it() -> None:
    versions = BACKEND / "alembic" / "versions"
    files = sorted(versions.glob("*.py"))
    assert files, f"no migrations found under {versions}; the scan would be vacuous"
    offenders = [
        p.name
        for p in files
        if any(INDEX_NAME in v for v in _executed_strings(p.read_text(encoding="utf-8")))
    ]
    assert offenders == [], (
        f"{INDEX_NAME} is built by a migration: {offenders}. Gotcha #31: build it "
        "by the attended CREATE INDEX CONCURRENTLY packet, never in the release phase."
    )
