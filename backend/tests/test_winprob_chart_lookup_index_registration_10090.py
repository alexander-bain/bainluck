"""#10090: the chart-lookup index is DECLARED in the model and BUILT only by hand.

PILLAR: TRUTH / FORMATTING. SHIP: a live game's chart follows Polymarket moves
within seconds, not ~95 minutes late, because each chart point stops reading
its event's whole history.

Production 2026-10-30 ~21:04Z (`pg_stat_statements`, 21.8 s window): the
ordered chart writer's previous-row lookup averaged 237 ms, 226 ms of it disk
reads (167 blocks per call). Every other statement of the point's transaction
took under 1 ms. `win_prob_snapshots` (3,968 MB heap) has no index that ends in
``captured_at`` behind ``(event_id, source)``, so each lookup fetched the
series and sorted it. The Polymarket writer paid ~3.2 points a second against
about as many owed, and 17,1xx rows sat in ``owed_chart_points``. Real-PG
proof: ``tests/integration/test_owed_chart_custody_11181_pg.py`` (the two
``…_lookup_reads_one_row_not_the_series`` cases). Runbook:
``artifacts/latency-10090-pm-live-chart-points-20261030/RUNBOOK-ix_winprob_event_source_captured.md``.

``backend/alembic/env.py`` has no ``include_object`` filter, so an index that
exists in the database but not in ``models.py`` becomes an ``op.drop_index``
in the next autogenerated revision. Pinned here, as for #2408 and #11676:

1. The declared definition: exactly ``(event_id, source, captured_at)``,
   non-unique, no predicate, no INCLUDE.
2. The compiled Postgres DDL is the runbook's statement minus CONCURRENTLY
   (and minus the default schema and method Postgres prints back).
3. No migration executes it. Gotcha #31: a concurrent build inside the release
   phase is the May 22 outage; a plain one locks out every chart INSERT.

No database is needed. A guard for an attended index must not skip on the
machine that would change it.
"""

from __future__ import annotations

import ast
from pathlib import Path

from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex

from app.models.models import WinProbSnapshot

INDEX_NAME = "ix_winprob_event_source_captured"
# The `pg_indexes.indexdef` the runbook's post-check 1 must read back.
RUNBOOK_INDEXDEF = (
    "CREATE INDEX ix_winprob_event_source_captured ON public.win_prob_snapshots "
    "USING btree (event_id, source, captured_at)"
)
# The same statement as SQLAlchemy compiles it: no schema, default method.
EXPECTED_PG_DDL = (
    "CREATE INDEX ix_winprob_event_source_captured ON win_prob_snapshots "
    "(event_id, source, captured_at)"
)

BACKEND = Path(__file__).resolve().parents[1]
RUNBOOK = (
    BACKEND.parent / "artifacts" / "latency-10090-pm-live-chart-points-20261030"
    / "RUNBOOK-ix_winprob_event_source_captured.md"
)


def _the_index():
    matches = [i for i in WinProbSnapshot.__table__.indexes if i.name == INDEX_NAME]
    assert len(matches) == 1, (
        f"{INDEX_NAME} must be declared exactly once on WinProbSnapshot; found "
        f"{len(matches)}. Without the declaration the first --autogenerate after "
        "the attended build proposes dropping it."
    )
    return matches[0]


def _squash(sql: str) -> str:
    return " ".join(sql.split())


def test_the_declared_index_is_the_reviewed_definition() -> None:
    idx = _the_index()
    assert [c.name for c in idx.columns] == ["event_id", "source", "captured_at"]
    assert idx.unique is False
    assert idx.dialect_options["postgresql"]["where"] is None
    assert not idx.dialect_options["postgresql"]["include"]
    assert idx.dialect_options["postgresql"]["using"] in (False, None, "btree")


def test_the_compiled_postgres_ddl_is_the_runbook_statement() -> None:
    ddl = _squash(str(CreateIndex(_the_index()).compile(dialect=postgresql.dialect())))
    assert ddl == EXPECTED_PG_DDL
    # Postgres prints the default schema and method back; nothing else differs.
    assert RUNBOOK_INDEXDEF.replace("public.", "").replace(" USING btree", "") == ddl
    runbook = _squash(RUNBOOK.read_text(encoding="utf-8"))
    assert (
        "CREATE INDEX CONCURRENTLY ix_winprob_event_source_captured ON "
        "public.win_prob_snapshots USING btree (event_id, source, captured_at);"
    ) in runbook
    assert RUNBOOK_INDEXDEF in runbook, "post-check 1 reads back this definition"


def _executed_strings(src: str) -> list[str]:
    """Every string literal in code that runs; docstrings and comments excluded."""
    tree = ast.parse(src)
    docstrings = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            first = node.body[0] if node.body else None
            if (
                isinstance(first, ast.Expr)
                and isinstance(first.value, ast.Constant)
                and isinstance(first.value.value, str)
            ):
                docstrings.add(id(first.value))
    return [
        n.value
        for n in ast.walk(tree)
        if isinstance(n, ast.Constant) and isinstance(n.value, str) and id(n) not in docstrings
    ]


def test_no_migration_builds_it() -> None:
    versions = BACKEND / "alembic" / "versions"
    files = sorted(versions.glob("*.py"))
    assert files, f"no migrations found under {versions}; the scan would be vacuous"
    offenders = [
        p.name
        for p in files
        if any(INDEX_NAME in v for v in _executed_strings(p.read_text(encoding="utf-8")))
    ]
    assert offenders == [], (
        f"{INDEX_NAME} is built by a migration: {offenders}. Gotcha #31: build it "
        "by the attended CREATE INDEX CONCURRENTLY runbook, never in the release phase."
    )
