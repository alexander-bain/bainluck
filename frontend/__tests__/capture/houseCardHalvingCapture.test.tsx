/**
 * UX-P163 — Discover stops halving a market's price, for Alex's eyeball.
 *
 * ═══ WHAT A READER SEES TODAY ═══
 *
 * `GET /api/feed` and `GET /api/futures/112903`, read within a minute of each other
 * on 2026-08-29, disagreed by FORTY-THREE POINTS about the same market:
 *
 *     Discover        Democratic Party  43%
 *     Market page     Democratic Party  85.5%
 *
 * Not a rounding drift — a halving. UX-P162 closed this class at the one-point
 * level; this is the same class at the point where it is impossible to miss.
 *
 * ═══ WHY (each step correct, the composition not) ═══
 *
 * The market holds 9 outcomes. Six are anonymized reserved slots ("Party A".."Party
 * F") priced 1.0, which `display_rank_order` DROPS. A seventh 1.0 row is named
 * "Other" — a field outcome, not a placeholder — so it is DEMOTED to the end
 * instead, which is the deliberate, tested contract. Three rows then remain, so
 * "the end" is still inside a `[:3]` card, and those three sum to exactly 2.0: the
 * inclusive top of `_feed_display_scale`'s band. Divisor 2.0, everything halved.
 *
 * The filter that made the card MORE honest is what pulled it into the scaling
 * regime that made it less so. With the six placeholders still present the sum is
 * ~8.0, above the band, and nothing would have been scaled at all.
 *
 * ═══ WHAT EVERY PANEL IS MADE OF ═══
 *
 * Both cards are the SHIPPED components with the app's own compiled stylesheet.
 * Neither payload is drawn by hand: `backend/tests/fixtures/uxp163_house_112903.json`
 * carries the DB rows, the BEFORE block (which reproduces the live feed byte for
 * byte) and the AFTER block, all three generated by running the real serializer
 * helpers over the real prices.
 *
 *   UX_CAPTURE_DIR=<dir> TZ=UTC npx jest --testPathPatterns=houseCardHalvingCapture
 *
 * With no env var set it is an ordinary test that renders every panel and asserts
 * the rig works, same as the sibling capture rigs.
 */

