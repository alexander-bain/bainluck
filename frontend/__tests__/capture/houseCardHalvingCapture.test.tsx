function panelThree(f: Fixture): string {
  const rows = f.db_outcomes
    .map((o) => {
      const placeholder = /^Party [A-Z]$/.test(o.name);
      const field = /^Other$/i.test(o.name);
      const fate = placeholder
        ? ["dropped — anonymized reserved slot", "ok"]
        : field
          ? ["dropped — no-bid field row at 1.0 (was: demoted, still printed)", "ok"]
          : ["printed", ""];
      return `<tr><td class="name">${o.name}</td><td class="mono">${o.current_probability}</td><td class="${fate[1]}">${fate[0]}</td></tr>`;
    })
    .join("\n");
  return `<section>
  <h2>Panel 3 — what happens to each of the nine rows</h2>
  <p class="note">Six placeholders were already dropped and that is what pulled the surviving
  sum from ~8.0 down to exactly 2.0 — the inclusive top of the normalization band. The seventh
  1.0 row is the one this queue removes.</p>
  <table>
    <thead><tr><th>Outcome</th><th>Book price</th><th>Fate on the card</th></tr></thead>
    <tbody>${rows}</tbody>
  </table>
</section>`;
}

