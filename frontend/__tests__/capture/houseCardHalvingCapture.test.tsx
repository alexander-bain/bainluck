type Served = {
  top_outcomes: Array<{
    id: number;
    name: string;
    probability: number | null;
    rank: number;
    rendered_percent: number | null;
  }>;
  card_sum_reason: string | null;
  display_scale: number;
};
type Fixture = {
  _provenance: Record<string, string | number>;
  db_outcomes: Array<{ id: number; name: string; current_probability: number | null }>;
  served_before: Served;
  served_after: Served;
};

function fixture(): Fixture {
  return JSON.parse(fs.readFileSync(FIXTURE, "utf8"));
}

/** The app's own compiled stylesheet, so the cards look like the product. */
function appStylesheet(): string {
  const dir = path.join(FRONTEND, ".next", "static", "css");
  try {
    return fs
      .readdirSync(dir)
      .filter((f) => f.endsWith(".css"))
      .map((f) => fs.readFileSync(path.join(dir, f), "utf8"))
      .join("\n");
  } catch {
    return "";
  }
}

/**
 * The card as the feed serves it. `outcome_count` stays 9 in BOTH arms: the raw
 * count is what the payload carries and the fix does not touch it, so a difference
 * here would be the rig editing the evidence.
 */
function asData(served: Served): FeedFuturesData {
  return {
    id: 112903,
    name: "Which party will win the House in 2026?",
    llm_sport_category: "politics",
    sport_name: "Politics",
    status: "open",
    source: "polymarket",
    source_count: 1,
    market_tier: 2,
    resolution_date: "2026-11-03T00:00:00Z",
    outcome_count: 9,
    group_type: "negrisk",
    top_outcomes: served.top_outcomes.map((o) => ({ movement: null, ...o })),
    card_sum_reason: served.card_sum_reason,
  } as unknown as FeedFuturesData;
}

function itemFor(data: FeedFuturesData): FeedItem {
  return {
    type: "futures",
    score: 76,
    reason: "",
    headline: "",
    data,
  } as unknown as FeedItem;
}

const HERO_RE = /(data-testid="futures-hero-probability"[^>]*>)([^<]+)(<)/;

function discoverHtml(data: FeedFuturesData): string {
  return renderToStaticMarkup(
    <FuturesCard
      item={itemFor(data)}
      data={data}
      liked={false}
      setLiked={() => {}}
      trending={false}
    />,
  );
}

function feedCardHtml(data: FeedFuturesData): string {
  return renderToStaticMarkup(<FeedCard item={itemFor(data)} />);
}

/**
 * UX-P046's sentinels come back HTML-escaped from `renderToStaticMarkup` (`&lt;1%`),
 * so anything comparing rendered text to a constant must unescape first or it fails
 * on the entity rather than on behaviour. Inherited trap, not a hypothetical.
 */
function unescape(s: string): string {
  return s.replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&");
}

function heroText(html: string): string | null {
  const m = html.match(HERO_RE);
  return m ? unescape(m[2]) : null;
}

/** Every whole percent the card prints, in document order. */
function printedPercents(html: string): string[] {
  return (html.match(/>(?:&lt;1%|&gt;99%|\d{1,3}%)</g) ?? []).map((m) =>
    unescape(m.slice(1, -1)),
  );
}

function bookRow(f: Fixture): string {
  const real = f.db_outcomes.filter((o) => !/^Party [A-Z]$/.test(o.name));
  return real
    .map((o) => `${o.name} <b>${o.current_probability}</b>`)
    .join(" &nbsp;·&nbsp; ");
}

