describe("UX-P163 capture", () => {
  it("the fixture's BEFORE block is the payload production actually served", () => {
    const f = fixture();
    expect(f.served_before.top_outcomes.map((o) => o.probability)).toEqual([
      0.4275, 0.0725, 0.5,
    ]);
    expect(f.served_before.display_scale).toBe(2.0);
  });

  it("Discover headlines 43% before and 86% after", () => {
    const f = fixture();
    expect(heroText(discoverHtml(asData(f.served_before)))).toBe("43%");
    expect(heroText(discoverHtml(asData(f.served_after)))).toBe("86%");
  });

  it("the untradeable row is gone from the LIST surface, not renumbered", () => {
    // Scoped to `FeedCard` deliberately. This market's `suggested_format` is
    // `binary_probability`, so Discover draws the hero-only variant and never
    // prints the outcome list — asserting "Other" against the Discover markup
    // would pass for the wrong reason (absent in both arms).
    const f = fixture();
    expect(feedCardHtml(asData(f.served_before))).toContain("Other");
    expect(feedCardHtml(asData(f.served_after))).not.toContain("Other");
  });

  it("the category-page surface moves with Discover", () => {
    const f = fixture();
    expect(feedCardHtml(asData(f.served_before))).toContain("43%");
    expect(feedCardHtml(asData(f.served_after))).toContain("86%");
  });

  it("renders the page, and writes it when UX_CAPTURE_DIR is set", () => {
    const html = page(fixture());
    expect(html).toContain("Panel 1");
    expect(html).toContain("Panel 2");
    expect(html).toContain("Panel 3");
    const dir = process.env.UX_CAPTURE_DIR;
    if (dir) {
      fs.mkdirSync(dir, { recursive: true });
      const out = path.join(dir, "ux-p163-house-card-halving.html");
      fs.writeFileSync(out, html, "utf8");
      // eslint-disable-next-line no-console
      console.log(`capture written: ${out}`);
    }
  });
});
