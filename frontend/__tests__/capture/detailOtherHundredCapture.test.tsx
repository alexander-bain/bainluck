/**
 * UX-P164 — the market page and search stop printing "Other 100%", for Alex's eyeball.
 *
 * ═══ WHAT A READER SEES TODAY ═══
 *
 * Read on the deployed build, 2026-08-29, both within a minute:
 *
 *     GET /api/futures/112903                    Democratic Party 85.5% · Republican Party 14.5% · Other 100%
 *     GET /api/events/search?q=which party...    Democratic Party 85.5% · Republican Party 14.5% · Other 100%
 *
 * "Other" is a no-bid ask — measured bid 0.0000 / ask 1.0000 (gotcha #17/#19) — on a
 * market whose real book is an 85.5/14.5 two-way. It prints as a 100% row sitting
 * underneath two real answers, on a US House election market.
 *
 * This is #993's OPENING SENTENCE, verbatim: "the futures DETAIL page showed
 * 'Other 100%'". Search was fixed then; the detail page was not, and the shared
 * module written to stop them diverging still let them agree on the wrong answer.
 *
 * ═══ WHY DEMOTION WAS NOT ENOUGH (and why this is not a re-litigation) ═══
 *
 * `display_rank_order` DEMOTES a dominant field row to the end rather than deleting
 * it. That is deliberate, pinned by `test_other_at_100_leaves_the_top_n`, and
 * UNCHANGED here. Demotion keeps the row out of a top-N slot only while the list is
 * LONGER than N — and neither of these surfaces is: the detail page renders the
 * whole list, and search has already sliced to `limit`. On a three-row market "the
 * end" is still on the page.
 *
 * ═══ WHAT EVERY PANEL IS MADE OF ═══
 *
 * Both arms are the SHIPPED components with the app's own compiled stylesheet.
 * `FuturesCard` is what `/search` renders (app/search/page.tsx:11) and it maps
 * `top_outcomes` through `OutcomeRow` — so the "Other 100%" row is a real render,
 * not a drawing. `FuturesHero` is the market page's headline.
 *
 * Neither payload is hand-written: `backend/tests/fixtures/uxp164_house_112903_detail.json`
 * was generated by running the real `app.utils.outcome_display` helpers over the DB
 * rows, and its `before` block reproduces both live payloads byte for byte.
 *
 *   UX_CAPTURE_DIR=<dir> TZ=UTC npx jest --testPathPatterns=detailOtherHundredCapture
 *
 * With no env var set it is an ordinary test that renders every panel and asserts
 * the rig works, same as the sibling capture rigs.
 */

