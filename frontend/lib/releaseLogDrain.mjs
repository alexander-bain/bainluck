import { timingSafeEqual } from 'node:crypto';

export const MAX_DRAIN_BYTES = 262144;

export function drainAuthorized(authorization, secret) {
  if (!secret || !authorization || !/^Basic /i.test(authorization)) return false;
  const actual = Buffer.from(authorization.slice(6), 'base64');
  const expected = Buffer.from(`logplex:${secret}`);
  return actual.length === expected.length && timingSafeEqual(actual, expected);
}

export async function handleLogDrain({ body, authorization, secret, forward }) {
  if (!drainAuthorized(authorization, secret)) return { status: 401, body: { error: 'invalid drain authorization' } };
  if (body.length > MAX_DRAIN_BYTES) return { status: 413, body: { error: 'drain body exceeds limit' } };
  // Heroku sends all sources. Router lines generated by the backend collector
  // must stop here, or a drain directly into Heroku would recursively log itself.
  if (!body.includes(Buffer.from('worker-ws')) && !body.includes(Buffer.from('logplex'))) {
    return { status: 202, body: { ignored: true } };
  }
  try {
    await forward(body);
    return { status: 202, body: { accepted: true } };
  } catch {
    return { status: 503, body: { error: 'durable log collector unavailable' } };
  }
}
