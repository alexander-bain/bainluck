    /// Every point is its golfer's own retained close, none after the selected
    /// hour or the boundary; every readout figure is its golfer's own close at
    /// the selected hour; every movement row has both exact endpoints; no
    /// chooser card carries a result or a later preview point.
    private static func payloadViolations(_ input: GolfPreTournamentEventPageInput10868) -> [String] {
        var found: [String] = []
        let history = input.history
        let selected = selectedHour(history)
        for series in history.series {
            guard let golfer = golfers.first(where: { $0.ticker == series.id }) else {
                found.append("foreign series: \(series.id)")
                continue
            }
            if series.choose?.id != "highlight.\(golfer.ticker)" { found.append("choose names another golfer: \(series.id)") }
            for point in series.runs.flatMap(\.points) {
                guard let close = points(golfer).first(where: { pointID(golfer, $0.t) == point.id }),
                      x(close.t) == point.x, close.probability == point.probability else {
                    found.append("not its own close: \(point.id)")
                    continue
                }
                if close.t > boundary { found.append("after the boundary: \(point.id)") }
                if let selected, close.t > selected { found.append("after the selected hour: \(point.id)") }
            }
        }
        let view = GolfPreTournamentEventPagePresentation10868(input: input)
        for entry in view.readoutsContent(reader: false).entries {
            guard let golfer = golfers.first(where: { $0.ticker == entry.series.id }) else { continue }
            for slot in entry.slots {
                guard case .figure(let figure, let provenance) = slot.display else { continue }
                if !points(golfer).contains(where: { $0.t == selected && Self.figure($0.probability) == figure && Self.provenance($0.t) == provenance }) {
                    found.append("figure not its own at the selected hour: \(entry.series.id) \(figure)")
                }
            }
        }
        if let movement = input.movement?.movement, let selected {
            for slot in movement.displayed {
                let pairs = movement.pairs.filter { $0.ref == slot.ref }
                guard let golfer = golfers.first(where: { $0.ticker == slot.ref.outcomeID }),
                      pairs.count == 1, let earlier = pairs[0].before, let later = pairs[0].later else {
                    found.append("a row without both endpoints: \(slot.label)")
                    continue
                }
                if point(golfer, selected - 24 * hour)?.probability != earlier.probability
                    || earlier.reading.value != .recorded(text: figure(earlier.probability), detail: provenance(selected - 24 * hour)) {
                    found.append("earlier endpoint is not exactly 24 hours before: \(slot.label)")
                }
                if point(golfer, selected)?.probability != later.probability
                    || later.reading.value != .recorded(text: figure(later.probability), detail: provenance(selected)) {
                    found.append("later endpoint is not the selected hour: \(slot.label)")
                }
            }
        }
        for original in input.chooser?.catalogue ?? [] {
            if original.result != nil { found.append("result: \(original.name)") }
            if let selected, original.preview.history?.segments.joined().contains(where: { $0.time > x(selected) }) == true {
                found.append("chooser preview after the selected hour: \(original.name)")
            }
        }
        return found
    }

