        XCTAssertEqual(none.chooserPresentation?.browse?.emptyGroupWords, "No golfers on this page")
        XCTAssertNil(none.chooserNavigation?.navigation.previous)
        XCTAssertNil(none.chooserNavigation?.navigation.next)

