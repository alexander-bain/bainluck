    /// No figure sits under a current, live, settled, score or projection
    /// label, and no reachable sentence makes such a claim un-negated.
    private static func claims(_ input: GolfPreTournamentEventPageInput10868,
                               originals: FieldEventPageOriginals10868?) -> [String] {
        var found: [String] = []
        var figureLabels: [String] = []
        let view = GolfPreTournamentEventPagePresentation10868(input: input)
        for reader in [false, true] {
            figureLabels += view.readoutsContent(reader: reader).entries.flatMap(\.slots)
                .filter { if case .figure = $0.display { return true }; return false }.map(\.label)
        }
        if let movement = view.movementContent(reader: false) {
            for row in GolfBeforeMovementModel10868(movement.input).rows {
                for endpoint in [row.before, row.later] {
                    if case .reading(let reading)? = endpoint, case .recorded = reading.value { figureLabels.append(reading.label) }
                }
            }
        }
        for original in input.chooser?.catalogue ?? [] {
            figureLabels += original.plan.readings.filter { if case .recorded = $0.value { return true }; return false }.map(\.label)
            if let result = original.result { found.append("result: \(original.name) \(result.words)") }
        }
        if let catalogue = originals?.catalogue {
            for original in catalogue.originals {
                if case .comparison(.current) = original.mode { found.append("current mode: \(original.identity.market)") }
                if original.mode == .result || original.grade != nil { found.append("settled: \(original.identity.market)") }
                let content = Originals.content(catalogue: catalogue, selection: Originals.Selection(scope: catalogue.scope, identity: original.identity))
                figureLabels += content?.readings.filter(\.isValue).map(\.label) ?? []
            }
        }
        found += figureLabels.filter { matches($0, forbiddenClaim) }.map { "figure under: \($0)" }
        for text in reachable(input, originals: originals) {
            for sentence in text.components(separatedBy: ". ") where matches(sentence, forbiddenClaim) && !matches(sentence, negation) {
                found.append("claim: \(sentence)")
            }
        }
        return found
    }

